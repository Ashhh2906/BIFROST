/**
 * Validate seed profiles in development and report any missing or invalid answers.
 */
export function validateSeedProfiles(profiles = SEED_PROFILES) {
  const errors = [];
  for (const profile of profiles) {
    for (const q of QUESTIONS) {
      const val = profile.answers?.[q.id];
      const validValues = QUESTION_MAP[q.id].options.map((o) => o.value);
      if (val === undefined || !validValues.includes(val)) {
        errors.push(`Profile "${profile.id}" has invalid/missing answer for "${q.id}": ${val}`);
      }
    }
  }
  return errors;
}

if (typeof import.meta !== 'undefined' && import.meta.env?.DEV) {
  const devErrors = validateSeedProfiles();
  if (devErrors.length > 0) {
    console.error('Seed profile validation errors:', devErrors);
  }
}
